// ─────────────────────────────────────────────────────────────────────────────
//  The dictionary, split by language for the app bundle
//
//    node i18n-split.mjs           write src/i18n/strings.en.js and strings.ar.js
//    node i18n-split.mjs --check   exit 1 if they are out of date
//
//  src/i18n/strings.js stays the one source: the translator's importer writes
//  it, the suites read it, and both languages sit side by side in it so a
//  missing Arabic line is visible. But the app shipped all of it in its first
//  chunk, so every reader downloaded the Arabic, and each batch of translation
//  made the app slower to open for the women reading English.
//
//  So the app reads two generated files instead: English, in the first chunk,
//  and Arabic, loaded only when Arabic is chosen (i18n/t.js `loadArabic`).
//  `npm run build` regenerates them first (prebuild), the importer regenerates
//  them after a translation is imported, and the i18n suite fails if the
//  committed copies have drifted from the source.
// ─────────────────────────────────────────────────────────────────────────────

import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath, pathToFileURL } from "node:url";
import { dirname, join } from "node:path";

const HERE = dirname(fileURLToPath(import.meta.url));
const SRC = join(HERE, "src/i18n/strings.js");
export const OUT_EN = join(HERE, "src/i18n/strings.en.js");
export const OUT_AR = join(HERE, "src/i18n/strings.ar.js");

const HEAD = (what) =>
  "// GENERATED by i18n-split.mjs from strings.js — do not edit by hand.\n" +
  `// ${what}\n`;

/** The two files' contents, from the dictionary as it is on disk now. */
export async function render() {
  // a fresh copy every time: the importer calls this after rewriting the file
  const { STRINGS } = await import(`${pathToFileURL(SRC).href}?t=${Date.now()}`);
  const keys = Object.keys(STRINGS);
  const line = (k, v) => `  ${k}: ${JSON.stringify(v)},`;
  const en = HEAD("English: in the first chunk, read by t() for every key.") +
    "export const EN = {\n" + keys.map((k) => line(k, STRINGS[k].en)).join("\n") + "\n};\n";
  const ar = HEAD("Arabic: loaded only when Arabic is chosen (t.js loadArabic). Keys with no Arabic yet are left out.") +
    "export const AR = {\n" + keys.filter((k) => STRINGS[k].ar).map((k) => line(k, STRINGS[k].ar)).join("\n") + "\n};\n";
  return { en, ar };
}

export async function writeSplit() {
  const { en, ar } = await render();
  writeFileSync(OUT_EN, en);
  writeFileSync(OUT_AR, ar);
}

export async function isCurrent() {
  const { en, ar } = await render();
  const read = (p) => { try { return readFileSync(p, "utf8"); } catch { return ""; } };
  return read(OUT_EN) === en && read(OUT_AR) === ar;
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  if (process.argv.includes("--check")) {
    const ok = await isCurrent();
    console.log(ok ? "strings.en.js and strings.ar.js match strings.js"
                   : "strings.en.js / strings.ar.js are out of date: run node i18n-split.mjs");
    process.exit(ok ? 0 : 1);
  }
  await writeSplit();
  console.log("wrote src/i18n/strings.en.js and src/i18n/strings.ar.js");
}
